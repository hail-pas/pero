#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVICE="__entity_postprocess_test"
SERVICE_DIR="${REPO_ROOT}/services/${SERVICE}"
DB_DIR="${SERVICE_DIR}/src/db"
ENTITY_DIR="${DB_DIR}/entity"

cleanup() {
    rm -rf "$SERVICE_DIR"
}
trap cleanup EXIT

fail() {
    echo "FAIL: $*" >&2
    exit 1
}

assert_contains() {
    local file="$1"
    local expected="$2"

    grep -Fq "$expected" "$file" || fail "expected '$expected' in $file"
}

assert_not_contains() {
    local file="$1"
    local unexpected="$2"

    if grep -Fq "$unexpected" "$file"; then
        fail "did not expect '$unexpected' in $file"
    fi
}

cleanup
mkdir -p "$ENTITY_DIR"

cat >"${ENTITY_DIR}/login_events.rs" <<'RS'
//! `SeaORM` Entity, @generated by sea-orm-codegen 2.0

use super::sea_orm_active_enums::LoginEventType;
use sea_orm::entity::prelude::*;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, PartialEq, Eq, DeriveEntityModel, Serialize, Deserialize)]
#[sea_orm(table_name = "login_events")]
pub struct Model {
    #[sea_orm(primary_key, auto_increment = false)]
    pub id: Uuid,
    pub event_type: LoginEventType,
    #[sea_orm(column_type = "custom(\"inet\")", select_as = "text", nullable)]
    pub ip: Option<String>,
}
RS

cat >"${ENTITY_DIR}/users.rs" <<'RS'
//! `SeaORM` Entity, @generated by sea-orm-codegen 2.0

use sea_orm::entity::prelude::*;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, PartialEq, Eq, DeriveEntityModel, Serialize, Deserialize)]
#[sea_orm(table_name = "users")]
pub struct Model {
    #[sea_orm(primary_key, auto_increment = false)]
    pub id: Uuid,
    #[sea_orm(
        ignore,
        column_type = "custom(\"citext\")",
        select_as = "text",
        nullable
    )]
    pub email: Option<String>,
}
RS

cat >"${ENTITY_DIR}/sea_orm_active_enums.rs" <<'RS'
//! `SeaORM` Entity, @generated by sea-orm-codegen 2.0

#[derive(Debug)]
pub enum LoginEventType {
    Login,
}
RS

cat >"${ENTITY_DIR}/mod.rs" <<'RS'
pub mod login_events;
pub mod sea_orm_active_enums;
pub mod users;
RS

"${REPO_ROOT}/scripts/generate-entity.sh" --postprocess-only "$SERVICE"

assert_contains "${ENTITY_DIR}/login_events.rs" "use super::super::enums::LoginEventType;"
assert_contains "${ENTITY_DIR}/login_events.rs" "use ipnetwork::IpNetwork;"
assert_contains "${ENTITY_DIR}/login_events.rs" "pub ip: Option<IpNetwork>,"
assert_not_contains "${ENTITY_DIR}/login_events.rs" "select_as = \"text\""

assert_contains "${ENTITY_DIR}/users.rs" "column_type = \"custom(\\\"citext\\\")\""
assert_not_contains "${ENTITY_DIR}/users.rs" "ignore,"

test -f "${DB_DIR}/enums.rs" || fail "expected enum file to move into db/enums.rs"
assert_not_contains "${ENTITY_DIR}/mod.rs" "sea_orm_active_enums"

echo "generate_entity_postprocess_test: ok"
